import { createHash } from "node:crypto";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";

import StyleDictionary from "style-dictionary";
import { formats, transformGroups } from "style-dictionary/enums";

import { validateContractFile } from "../../theme-contracts/src/contracts";

const extensionKey = "dev.jwsoft.g5-theme";
const generatedMarker = "@generated by @jwsoft/theme-tokens; do not edit";

type JsonRecord = Record<string, unknown>;

export interface TokenBuildResult {
  sourceSha256: string;
  tokensCss: string;
  tailwindThemeCss: string;
}

function asRecord(value: unknown, label: string): JsonRecord {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object`);
  }
  return value as JsonRecord;
}

function collectTokenPaths(node: JsonRecord, prefix: string[] = [], found = new Set<string>()): Set<string> {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    const child = asRecord(value, [...prefix, key].join("."));
    if (Object.hasOwn(child, "$value")) found.add([...prefix, key].join("."));
    else collectTokenPaths(child, [...prefix, key], found);
  }
  return found;
}

function readTailwindMap(tokens: JsonRecord): Record<string, string> {
  const extensions = asRecord(tokens.$extensions, "$extensions");
  const jwsoft = asRecord(extensions[extensionKey], `$extensions.${extensionKey}`);
  return asRecord(jwsoft.tailwind, `$extensions.${extensionKey}.tailwind`) as Record<string, string>;
}

function aliasPath(alias: string): string {
  return alias.slice(1, -1);
}

function cssVariableForAlias(alias: string): string {
  return `--jw-${aliasPath(alias).replaceAll(".", "-")}`;
}

function buildTailwindTheme(tailwindMap: Record<string, string>, sourceSha256: string): string {
  const declarations = Object.entries(tailwindMap)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, alias]) => `  ${name}: var(${cssVariableForAlias(alias)});`)
    .join("\n");

  return `/* ${generatedMarker}; source-sha256: ${sourceSha256} */\n@theme inline {\n${declarations}\n}\n`;
}

function addHeader(css: string, sourceSha256: string): string {
  return `/* ${generatedMarker}; source-sha256: ${sourceSha256} */\n${css.trimStart()}`;
}

export async function buildThemeTokens(sourceFile: string, outputDir: string): Promise<TokenBuildResult> {
  const absoluteSource = resolve(sourceFile);
  if (basename(absoluteSource) !== "theme.tokens.json") {
    throw new Error("token source filename must be theme.tokens.json");
  }

  const failures = await validateContractFile(absoluteSource);
  if (failures.length) throw new Error(failures.map((failure) => failure.message).join("; "));

  const source = await readFile(absoluteSource);
  const sourceSha256 = createHash("sha256").update(source).digest("hex");
  const tokens = asRecord(JSON.parse(source.toString("utf8")), "token source");
  const tokenPaths = collectTokenPaths(tokens);
  const tailwindMap = readTailwindMap(tokens);

  for (const [name, alias] of Object.entries(tailwindMap)) {
    const path = aliasPath(alias);
    if (!tokenPaths.has(path)) throw new Error(`Tailwind variable ${name} references missing token ${path}`);
  }

  const temporaryDir = await mkdtemp(join(tmpdir(), "jwsoft-theme-tokens-"));
  try {
    const dictionary = new StyleDictionary({
      source: [absoluteSource],
      usesDtcg: true,
      platforms: {
        css: {
          transformGroup: transformGroups.css,
          prefix: "jw",
          buildPath: `${temporaryDir}/`,
          files: [
            {
              destination: "tokens.css",
              format: formats.cssVariables,
              options: {
                outputReferences: true,
                showFileHeader: false
              }
            }
          ]
        }
      }
    }, { verbosity: "silent" });
    await dictionary.buildAllPlatforms();

    const rawTokensCss = await readFile(join(temporaryDir, "tokens.css"), "utf8");
    const tokensCss = addHeader(rawTokensCss, sourceSha256);
    const tailwindThemeCss = buildTailwindTheme(tailwindMap, sourceSha256);

    await mkdir(outputDir, { recursive: true });
    await Promise.all([
      writeFile(join(outputDir, "tokens.css"), tokensCss),
      writeFile(join(outputDir, "tailwind-theme.css"), tailwindThemeCss)
    ]);

    return { sourceSha256, tokensCss, tailwindThemeCss };
  } finally {
    await rm(temporaryDir, { recursive: true, force: true });
  }
}

export async function checkThemeTokens(sourceFile: string, outputDir: string): Promise<void> {
  const temporaryDir = await mkdtemp(join(tmpdir(), "jwsoft-theme-tokens-check-"));
  try {
    await buildThemeTokens(sourceFile, temporaryDir);
    for (const filename of ["tokens.css", "tailwind-theme.css"]) {
      const [expected, actual] = await Promise.all([
        readFile(join(temporaryDir, filename), "utf8"),
        readFile(join(outputDir, filename), "utf8").catch(() => "")
      ]);
      if (actual !== expected) throw new Error(`${filename} is missing or stale; rebuild theme tokens`);
    }
  } finally {
    await rm(temporaryDir, { recursive: true, force: true });
  }
}
